def sub_word(x):
    return (
        int(SBOX[(x >> 24) & 0xFF]) << 24
        | int(SBOX[(x >> 16) & 0xFF]) << 16
        | int(SBOX[(x >> 8) & 0xFF]) << 8
        | int(SBOX[x & 0xFF])
    )


def rot_word(x):
    return ((x << 8) & 0xFFFFFFFF) | (x >> 24)


def invert_last_round_key(last_round_key):
    words = [0] * 44
    for i in range(4):
        words[40 + i] = int.from_bytes(last_round_key[4 * i:4 * i + 4], "big")
    for i in range(43, 3, -1):
        if i % 4 == 0:
            words[i - 4] = words[i] ^ sub_word(rot_word(words[i - 1])) ^ RCON[i // 4 - 1]
        else:
            words[i - 4] = words[i] ^ words[i - 1]
    return b"".join(words[i].to_bytes(4, "big") for i in range(4))


def load_traces(path):
    ciphers = []
    timings = []
    with path.open() as f:
        next(f)
        for line in f:
            ct, t = line.strip().split(",")
            ciphers.append(np.frombuffer(bytes.fromhex(ct), dtype=np.uint8).reshape(32, 16))
            timings.append(float(t))
    return np.stack(ciphers), np.array(timings, dtype=np.float64)


def score_byte(cipher_bytes, timings, chunk=32):
    centered_timing = timings - timings.mean()
    timing_norm = np.sqrt(np.sum(centered_timing * centered_timing))
    scores = np.zeros(256, dtype=np.float64)
    guesses = np.arange(256, dtype=np.uint8)
    for start in range(0, 256, chunk):
        current = guesses[start:start + chunk]
        values = np.bitwise_xor(cipher_bytes[..., None], current[None, None, :])
        lines = np.right_shift(INV_SBOX[values], 4).astype(np.uint16)
        masks = np.left_shift(np.uint16(1), lines)
        counts = BITCOUNT16[np.bitwise_or.reduce(masks, axis=1)].astype(np.float64)
        counts -= counts.mean(axis=0, keepdims=True)
        numerators = np.sum(counts * centered_timing[:, None], axis=0)
        denominators = np.sqrt(np.sum(counts * counts, axis=0)) * timing_norm
        scores[start:start + len(current)] = np.divide(
            numerators,
            denominators,
            out=np.zeros_like(numerators),
            where=denominators != 0,
        )
    return scores


trace_path = Path("aes_traces.csv")
ciphertexts, timings = load_traces(trace_path)
recovered = bytearray(16)

print("Loaded traces", len(timings))
for byte_index in range(16):
    cipher_position = int(INV_SHIFT[byte_index])
    scores = score_byte(ciphertexts[:, :, cipher_position], timings)
    guess = int(np.argmax(scores))
    recovered[byte_index] = guess
    print(f"byte {byte_index:02d} guess {guess:02x} score {scores[guess]:.6f}")

original = invert_last_round_key(bytes(recovered))

print("Best guess last round key", bytes(recovered).hex())
